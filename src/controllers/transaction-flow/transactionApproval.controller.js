exports.createReceiptApprovalRequest = async (req, res) => {
  const connection = await db.getConnection();
  try {
    await connection.beginTransaction();
    const data = req.body;
    const employeeId = req.user.id;

    const config = await transactionApprovalConfigModel.getApprovalConfigByEmployee(employeeId);

    if (!config) {
      throw new Error("Approval configuration not found");
    }
    if (!config.junior_accountant_id) {
      throw new Error("Junior Accountant not assigned");
    }
    if (!config.senior_accountant_id) {
      throw new Error("Senior Accountant not assigned");
    }

    let attachment = null;
    if (req.file) {
      const uploaded = await uploadFileToMinio(req.file, "txn_receipt");
      attachment = uploaded.object_path;
    }

    const [userRows] = await connection.query(
      `SELECT name FROM users WHERE id = ?`,
      [employeeId],
    );
    const employeeName = userRows[0]?.name || "Employee";

    // entries may arrive as a JSON string (multipart) or object (json body)
    const payload = {
      ...data,
      entries:
        typeof data.entries === "string"
          ? JSON.parse(data.entries || "[]")
          : data.entries || [],
      attachment,
    };

    const approvalId = await transactionApprovalModel.createApprovalRequest(connection, {
      transaction_type: "RECEIPT",
      created_by: employeeId,
      junior_accountant_id: config.junior_accountant_id,
      dispatcher_id: config.dispatcher_id || null, // unused in receipt flow, kept for schema consistency
      senior_accountant_id: config.senior_accountant_id,
      current_approver_id: config.junior_accountant_id,
      approval_level: "JUNIOR",
      payload_json: payload,
      current_status_message: `Pending at Junior Accountant ${config.junior_accountant_name}.`,
    });

    await transactionApprovalModel.createHistory(connection, {
      approval_id: approvalId,
      action: "CREATED",
      action_by: employeeId,
      action_level: "EMPLOYEE",
      remarks: "Receipt request submitted",
    });

    await transactionApprovalModel.createNotification(connection, {
      user_id: config.junior_accountant_id,
      approval_id: approvalId,
      module_type: "RECEIPT",
      notification_category: "APPROVAL",
      title: "New Receipt Request",
      message: `Receipt request generated by ${employeeName}.`,
      generated_by_id: employeeId,
      generated_by_name: employeeName,
    });

    await transactionApprovalModel.createNotification(connection, {
      user_id: employeeId,
      approval_id: approvalId,
      module_type: "RECEIPT",
      notification_category: "STATUS",
      title: "Receipt Request Status",
      message: `Your receipt request is pending for approval by ${config.junior_accountant_name}.`,
      generated_by_id: employeeId,
      generated_by_name: employeeName,
    });

    await connection.commit();

    return res.status(201).json({
      success: true,
      message: "Receipt request submitted for approval",
      approval_id: approvalId,
    });
  } catch (error) {
    await connection.rollback();
    return res.status(500).json({ success: false, message: error.message });
  } finally {
    connection.release();
  }
};

