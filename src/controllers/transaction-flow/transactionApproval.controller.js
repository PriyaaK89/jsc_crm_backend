exports.getNotifications = async (req, res) => {
  try {
    const userId = req.user.id;
    const { module_type, notification_category } = req.query;

    const notifications = await transactionApprovalModel.getNotifications(
      userId,
      module_type || null,
      notification_category || null,
    );

    // Generate presigned URL for notification attachments
    const notificationsWithPresignedUrls = await Promise.all(
      notifications.map(async (notification) => {
        let attachment_url = null;

        if (notification.attachment) {
          try {
            attachment_url = await getPresignedUrl(
              notification.attachment,
              60 * 60, // URL valid for 1 hour
            );
          } catch (error) {
            console.error(
              `Failed to generate presigned URL for notification ${notification.id}:`,
              error.message,
            );
          }
        }

        return {
          ...notification,
          attachment_url,
        };
      }),
    );

    return res.status(200).json({
      success: true,
      totalRecords: notificationsWithPresignedUrls.length,
      data: notificationsWithPresignedUrls,
    });
  } catch (error) {
    return res.status(500).json({
      success: false,
      message: error.message,
    });
  }
};

